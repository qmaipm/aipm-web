export const THEMES: Theme[] = ["AI 落地方法", "物业 AI 化", "OBC 模式"];

export function getArticle(slug: string): Article {
  const a = ARTICLES.find((x) => x.slug === slug);
  if (!a) throw new Error(`未知文章: ${slug}`);
  return a;
}

// 文章页共享 metadata:canonical 指向文章自身、og:type=article 并带
// published_time / author / section / tag(og:url、canonical 为相对路径,
// 由根布局的 metadataBase 按当前环境解析成绝对地址)。
// title/description 由各文章页传入(页面 SEO 文案与登记表 desc 口径不同)。
export function articleMetadata(
  slug: string,
  page: { title: string; description: string }
): Metadata {
  const a = getArticle(slug);
  const url = `/insights/${slug}`;
  const publishedISO = a.date.replace(/\./g, "-");
  return {
    title: page.title,
    description: page.description,
    alternates: { canonical: url },
    openGraph: {
      type: "article",
      locale: "zh_CN",
      siteName: "启盟科技 FMClaw™",
      url,
      title: page.title,
      description: page.description,
      publishedTime: publishedISO,
      modifiedTime: publishedISO,
      authors: [a.by],
      section: a.theme,
      tags: a.series ? [a.theme, a.series] : [a.theme],
      ...(a.cover ? { images: [a.cover] } : {}),
    },
  };
}

// 同主题优先,补足到 n 篇
export function getRecommended(slug: string, n = 3): Article[] {
  const cur = getArticle(slug);
  const others = ARTICLES.filter((a) => a.slug !== slug);
  const sameTheme = others.filter((a) => a.theme === cur.theme);
  const rest = others.filter((a) => a.theme !== cur.theme);
  return [...sameTheme, ...rest].slice(0, n);
}
